"""Имена служебных AMQP-заголовков."""

from typing import Final


class MessageHeaders:
    """Пространство имён служебных заголовков сообщений.

    Заголовки несут метаданные доставки, которые не относятся к бизнес-
    содержимому события и поэтому не попадают в тело сообщения.
    """

    EVENT_TYPE: Final[str] = "x-event-type"
    """Тип интеграционного события, например ``payment.created.v1``."""

    ATTEMPT: Final[str] = "x-attempt"
    """Номер попытки обработки (с единицы); отсутствие означает первую."""

    LAST_ERROR: Final[str] = "x-last-error"
    """Краткое описание ошибки предыдущей попытки — для диагностики."""
