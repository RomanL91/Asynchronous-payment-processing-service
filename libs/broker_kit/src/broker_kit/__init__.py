"""Общий messaging-слой сервисов процессинга платежей.

Пакет — это «шасси» межсервисного взаимодействия через RabbitMQ.
Он выделен в библиотеку, чтобы оба сервиса (payments-service и
processor-service) одинаково понимали:

* ``contracts``   — формат интеграционных событий и служебных заголовков;
* ``topology``    — обменники, рабочие, retry- и DLQ-очереди;
* ``reliability`` — политику обработки ошибок: ретраи с экспоненциальной
  задержкой и отправку в Dead Letter Queue;
* ``settings`` / ``factory`` — единые настройки и сборку брокера.

Параметры топологии (TTL retry-очередей) должны совпадать у всех
сервисов, иначе RabbitMQ ответит ``PRECONDITION_FAILED`` при повторном
объявлении очереди. Общая библиотека гарантирует это по построению.
"""
