"""Базовые исключения, задающие семантику повторных попыток."""


class MessageProcessingError(Exception):
    """Базовая ошибка обработки сообщения."""


class TransientError(MessageProcessingError):
    """Временная ошибка: повторная попытка имеет смысл.

    Примеры: таймаут, 5xx внешнего сервиса, недоступность сети.
    """


class PermanentError(MessageProcessingError):
    """Постоянная ошибка: повтор даст тот же результат.

    Такое сообщение сразу уходит в DLQ, не тратя попытки.
    Примеры: невалидное тело, 4xx внешнего сервиса, отсутствующая сущность.
    """
